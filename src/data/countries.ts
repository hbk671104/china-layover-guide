/**
 * Case-insensitive search over the country list.
 *
 * Prefix matches are ranked above mid-string matches so typing "ind" surfaces
 * "India" and "Indonesia" before something like "British Indian Ocean Territory"
 * would (if it were in the list). Returns the full list for an empty query.
 */
export function filterCountries(query: string, countries: string[] = allCountries): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return countries;

  const starts: string[] = [];
  const contains: string[] = [];

  for (const country of countries) {
    const lower = country.toLowerCase();
    if (lower.startsWith(q)) {
      starts.push(country);
    } else if (lower.includes(q)) {
      contains.push(country);
    }
  }

  return [...starts, ...contains];
}
